"""Compile the checked-in, licensed observed-loot snapshot; no network at build time."""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = json.loads((ROOT / "data/everloot-snapshot.json").read_text())
    if source["gameFlavor"] != "forever" or source["attribution"]["licence"] != "CC BY-SA 4.0":
        raise ValueError("Unexpected data scope or licence")
    grouped = defaultdict(list)
    for row in source["rates"]:
        if not (row["public"] and row["reporters"] >= 3 and row["kills"] > 0 and 0 <= row["rate"] <= 1):
            raise ValueError("Unconfirmed or invalid data")
        if abs(row["drops"] / row["kills"] - row["rate"]) > 1e-9:
            raise ValueError("Inconsistent window rate")
        grouped[row["sourceNpcId"]].append(row)
    lines = [
        "-- GENERATED by scripts/build_catalog.py. Derived data: CC BY-SA 4.0.",
        "-- Data from Everloot (https://everloot.app), CC BY-SA 4.0.",
        "-- Source: https://everloot.app/api/rollups/drops | NPC sources only.",
        "-- Rates describe observed loot windows, NOT kill probabilities. Quantities/conditions unknown.",
        "-- Legacy untyped windows may be present. This partial catalog is excluded from kill forecasts.",
        "local _, G = ...",
        "G.Catalog.community = {" + f'dataAsOf = {json.dumps(source["dataAsOf"])}, npcCount = {len(grouped)}, '
        + f'rowCount = {len(source["rates"])}, credit = {json.dumps(source["attribution"]["credit"])}' + "}",
    ]
    for npc, rows in sorted(grouped.items()):
        lines.append(f"G.Catalog.entries[{npc}] = {{")
        for row in sorted(rows, key=lambda r: r["itemId"]):
            lines.append("    {" + f'itemID = {row["itemId"]}, probability = {row["rate"]:.16g}, '
                         + f'windowCount = {row["kills"]}, dropWindowCount = {row["drops"]}, reporters = {row["reporters"]}, '
                         + 'category = "observed", condition = "unknown", variantPolicy = "base-only", source = "Everloot"},')
        lines.append("}")
    target = ROOT / "GrindMeter/Data/CommunityCatalog.lua"
    target.write_text("\n".join(lines) + "\n")
    print(f"Catalog: {len(grouped)} NPCs, {len(source['rates'])} item-source rows; rates per loot window.")


if __name__ == "__main__":
    main()
